local Fixture = require("tests/nis_fixture")
local run, rect = Fixture.run, Fixture.rect

run("restart restores bounds, tab order and selection despite reverse plugin load order", function(f)
    local a = f:panel({ id = "a" })
    local b = f:panel({ id = "b", x = 500, height = 260 })
    assert(a:DockTo(b))
    a:SetSize(340, 260)
    b:SelectTab()
    assert(not pcall(f.panel, f, { id = "a" }), "duplicate live IDs must be rejected")
    a:Destroy(); b:Destroy()
    f:restart(); f:lock(true)

    b = f:panel({ id = "b", x = -10, xAnchor = 0.5, width = 600, dockTo = "new-default" })
    rect(b.root, 500, 100, 340, 260)
    assert(b._nisGroup == nil, "missing plugin leaves a usable standalone panel")
    local builds = 0
    a = f:panel({ id = "a", buildContent = function() builds = builds + 1 end })
    assert(a._nisGroup == b._nisGroup and a._nisGroup.active == b)
    assert(a._nisGroup.members[1] == b and a._nisGroup.members[2] == a, "saved order beats creation order")
    assert(a.content == nil and builds == 0, "inactive restoration must not allocate content")
    b:Destroy()
    assert(builds == 1, "survivor builds only when selected")
    a:SetSize(360, 280)
    b = f:panel({ id = "b" })
    rect(b.root, 500, 100, 360, 280)
    a:Undock()
    a:Destroy(); b:Destroy(); f:restart()
    a = f:panel({ id = "a", dockTo = "b" })
    b = f:panel({ id = "b", dockTo = "a" })
    assert(a._nisGroup == nil and b._nisGroup == nil, "saved undock overrides new defaults")
end)

run("deferred default docking and disabled membership survive restart", function(f)
    local a = f:panel({ id = "a", dockTo = "b" })
    local b = f:panel({ id = "b", x = 500, height = 260 })
    local c = f:panel({ id = "c", dockTo = "b" })
    assert(a._nisGroup == b._nisGroup and c._nisGroup == a._nisGroup)
    c:Hide()
    a:Destroy(); b:Destroy(); c:Destroy(); f:restart()
    a = f:panel({ id = "a" })
    c = f:panel({ id = "c" })
    b = f:panel({ id = "b" })
    assert(not c:IsActive() and c.content == nil and c._nisGroup == nil)
    a:SetSize(320, 280)
    f:lock(true)
    c:SetActive(true)
    assert(c._nisGroup == a._nisGroup and c._nisGroup.active == c)
    assert(c._nisGroup.members[3] == c, "reopening restores its tab slot")
    rect(c.root, 500, 100, 320, 280)
end)

run("only committed drag and resize bounds are saved and notified", function(f)
    local changes = {}
    local panel = f:panel({ id = "moving", onBoundsChange = function(_, x, y, width, height)
        changes[#changes + 1] = { x = x, y = y, width = width, height = height }
    end })
    f:begin(panel); f:move(panel, 500, 200)
    assert(#changes == 0 and f:saved("moving").x == 100)
    f:emit("KeyDown", { gameKey = GameKey.ESCAPE })
    rect(panel.root, 100, 100, 300, 200)
    f:begin(panel); f:move(panel, 500, 200); f:release(panel)
    rect(changes[1], 350, 194, 300, 200)
    f.fire(panel.dragLayer, ui.Hook.ONDRAGCOMPLETE)
    f.expect(#changes, 1, "duplicate completion must not notify twice")
    local edge = panel.resize.handles.e
    f.fire(edge, ui.Hook.ONCLICK, 2, 2)
    f.fire(edge, ui.Hook.ONHOLD, 32, 2)
    assert(#changes == 1 and f:saved("moving").width == 300)
    panel:Hide()
    rect(changes[2], 350, 194, 330, 200)
    f.fire(edge, ui.Hook.ONRELEASE)
    f.expect(#changes, 2, "interrupted resize commits exactly once")
    panel:Destroy(); f:restart()
    panel = f:panel({ id = "moving" })
    rect(panel.root, 350, 194, 330, 200)
    assert(not panel:IsActive(), "hidden state survives restart")
end)

run("closing during a drag saves disabled membership before callback destruction", function(f)
    local a = f:panel({ id = "a", onClose = function(owner) owner:Destroy() end })
    local b = f:panel({ id = "b", x = 500, height = 260 })
    assert(a:DockTo(b))
    f:begin(a); f:move(a, 200, 500); a:Close()
    local saved = f:saved("a")
    assert(saved.active == false and saved.group == f:saved("b").group)
    f.expect(saved.x, 500, "close cancels transient drag position")
    b:Destroy(); f:restart()
    a = f:panel({ id = "a" }); b = f:panel({ id = "b" })
    assert(not a:IsActive())
    a:Show()
    assert(a._nisGroup == b._nisGroup, "callback destruction must not forget tab membership")
end)

run("default docking and restart retain host bounds despite incompatible member limits", function(f)
    local source = f:panel({ id = "source", dockTo = "host", maxWidth = 220, minHeight = 420 })
    local host = f:panel({ id = "host", x = 500, width = 460, height = 260, minWidth = 430 })
    assert(source._nisGroup == host._nisGroup)
    rect(source.root, 500, 100, 460, 260)
    source:Destroy(); host:Destroy(); f:restart()
    host = f:panel({ id = "host", minWidth = 430 })
    source = f:panel({ id = "source", maxWidth = 220, minHeight = 420 })
    assert(source._nisGroup == host._nisGroup)
    rect(source.root, 500, 100, 460, 260)
    source:SetSize(160, 150)
    source:Hide()
    rect(host.root, 500, 100, 430, 150)
    f:lock(true); f:lock(false)
    source:Show()
    rect(source.root, 500, 100, 160, 150)
    source:Destroy(); host:Destroy(); f:restart()
    host = f:panel({ id = "host", minWidth = 430 })
    rect(host.root, 500, 100, 430, 150)
    source = f:panel({ id = "source", maxWidth = 220, minHeight = 420 })
    assert(source._nisGroup == host._nisGroup)
    rect(source.root, 500, 100, 160, 150)
    source:Undock()
    assert(source._nisGroup == nil and host._nisGroup == nil)
    rect(source.root, 500, 100, 160, 420)
    rect(host.root, 500, 100, 430, 150)
    f.expect(f:saved("source").height, 420, "detached page saves its restored minimum")
    f.expect(f:saved("host").width, 430, "standalone survivor saves its restored minimum")
    source:Destroy(); host:Destroy(); f:restart()
    source = f:panel({ id = "source", maxWidth = 220, minHeight = 420 })
    host = f:panel({ id = "host", minWidth = 430 })
    assert(source._nisGroup == nil and host._nisGroup == nil)
    rect(source.root, 500, 100, 160, 420)
    rect(host.root, 500, 100, 430, 150)
end)
